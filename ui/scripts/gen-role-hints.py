"""Generate ui/packages/shared/src/access/roleHints.generated.ts from the tenant role catalogue.

The roles the Entity job renders into every tenant namespace are defined in
eda/rulebooks/roles/entity_provision/vars/main.yml (entity_named_roles: spec_key,
crud_resources, read_resources). For each resource plural the UI needs to say
which role grants reading and which grants writing, so a disabled button or a
forbidden list can name the role (design section 6).

  python3 -I ui/scripts/gen-role-hints.py           write the file
  python3 -I ui/scripts/gen-role-hints.py --check   exit 1 when the file is out of date
"""
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "eda/rulebooks/roles/entity_provision/vars/main.yml"
TARGET = ROOT / "ui/packages/shared/src/access/roleHints.generated.ts"


def render():
    data = yaml.safe_load(SOURCE.read_text())
    roles = data.get("entity_named_roles") or []
    hints = {}
    order = []
    for role in roles:
        key = role["spec_key"]
        order.append(key)
        for plural in role.get("crud_resources") or []:
            h = hints.setdefault(plural, {"read": [], "write": []})
            for cls in ("read", "write"):
                if key not in h[cls]:
                    h[cls].append(key)
        for plural in role.get("read_resources") or []:
            h = hints.setdefault(plural, {"read": [], "write": []})
            if key not in h["read"]:
                h["read"].append(key)
    lines = [
        "// Generated by ui/scripts/gen-role-hints.py from",
        "// eda/rulebooks/roles/entity_provision/vars/main.yml. Do not edit by hand.",
        "",
        "/** Tenant role keys (Entity spec.namespaceRbac keys), in catalogue order. */",
        "export const TENANT_ROLE_KEYS = [",
    ]
    lines += [f"  '{k}'," for k in order]
    lines += [
        "] as const;",
        "",
        "export type TenantRoleKey = (typeof TENANT_ROLE_KEYS)[number];",
        "",
        "/** For each resource plural: the tenant roles that grant reading (get/list/watch) and writing (create/update/patch/delete). */",
        "export const ROLE_HINTS: Record<string, { read: TenantRoleKey[]; write: TenantRoleKey[] }> = {",
    ]
    for plural in sorted(hints):
        h = hints[plural]
        r = ", ".join(f"'{k}'" for k in h["read"])
        w = ", ".join(f"'{k}'" for k in h["write"])
        lines.append(f"  {plural}: {{ read: [{r}], write: [{w}] }},")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    out = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        cur = TARGET.read_text() if TARGET.exists() else ""
        if cur != out:
            print(f"{TARGET} is out of date: run python3 -I ui/scripts/gen-role-hints.py", file=sys.stderr)
            return 1
        print("role hints up to date")
        return 0
    TARGET.write_text(out)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
