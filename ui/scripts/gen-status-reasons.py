"""Generate ui/packages/shared/src/status/reasons.generated.ts from the reasons registry.

The status contract's reasons registry (one entry per condition reason: actor,
class, tenant-safe summary) lives in the Ansible collection that writes status:
eda/rulebooks/collections/ansible_collections/hybridsovereign/shc/plugins/module_utils/shc_status_reasons.py
The UI derives a phase only as a fallback (objects the status library has not
written yet) and must use the same reason classes and summaries, so the table
is generated from that file instead of being copied by hand.

  python3 -I ui/scripts/gen-status-reasons.py           write the file
  python3 -I ui/scripts/gen-status-reasons.py --check   exit 1 when the file is out of date
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "eda/rulebooks/collections/ansible_collections/hybridsovereign/shc/plugins/module_utils/shc_status_reasons.py"
TARGET = ROOT / "ui/packages/shared/src/status/reasons.generated.ts"


def load():
    # The registry is pure data without imports (its header says so); run it in an empty namespace.
    ns = {"__name__": "shc_status_reasons"}
    exec(compile(SOURCE.read_text(), str(SOURCE), "exec"), ns)  # noqa: S102 - repository file
    return ns


def render():
    ns = load()
    reasons = ns["REASONS"]
    lines = [
        "// Generated by ui/scripts/gen-status-reasons.py from",
        "// eda/rulebooks/collections/ansible_collections/hybridsovereign/shc/plugins/module_utils/shc_status_reasons.py.",
        "// Do not edit by hand.",
        "",
        "export type ReasonClass = 'ready' | 'progress' | 'waiting' | 'failed' | 'blocked';",
        "/** A = automatic (nothing to do), T = the tenant can act, P = the platform team acts. */",
        "export type ReasonActor = 'A' | 'T' | 'P';",
        "",
        "export interface ReasonEntry {",
        "  actor: ReasonActor;",
        "  class: ReasonClass;",
        "  summary: string;",
        "}",
        "",
        "export const REASONS: Record<string, ReasonEntry> = {",
    ]
    def entries(table):
        for name in sorted(table):
            e = table[name]
            lines.append(
                f"  {json.dumps(name)}: {{ actor: {json.dumps(e['actor'])}, class: {json.dumps(e['class'])}, "
                f"summary: {json.dumps(e['summary'], ensure_ascii=False)} }},"
            )

    entries(reasons)
    lines += [
        "};",
        "",
        "/** Reasons written on a part of a status (an egress family, a placement's IPv6 internet access), never",
        " *  as the Ready condition reason; they do not change the phase. */",
        "export const PART_REASONS: Record<string, ReasonEntry> = {",
    ]
    entries(ns.get("PART_REASONS", {}))
    lines += [
        "};",
        "",
        f"export const DELETE_REQUESTED_SUFFIX = {json.dumps(ns['DELETE_REQUESTED_SUFFIX'])};",
        "",
        "/** Fallback summary per phase. */",
        "export const PHASE_SUMMARIES: Record<string, string> = {",
    ]
    for phase, text in ns["PHASE_SUMMARIES"].items():
        lines.append(f"  {phase}: {json.dumps(text, ensure_ascii=False)},")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python3 -I ui/scripts/gen-status-reasons.py", file=sys.stderr)
            return 1
        print("status reasons up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(load()['REASONS'])} reasons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
