#!/usr/bin/env python3
"""Generate operator/primary/helm/templates/crds.yaml from the per-kind CRD sources.

Sources: operator/config/crd/bases/crd-<singular>.yaml, one CustomResourceDefinition per file.
The output wraps the sources, in file-name order and byte for byte (comments and formatting
survive), in the chart's `installCRDs` switch. Never edit crds.yaml by hand; edit a source and
run this script. A merge conflict in crds.yaml is resolved by regenerating it.

Each source must:
  - be named crd-<spec.names.singular>.yaml (any other file in the directory is an error),
  - hold exactly one apiextensions.k8s.io/v1 CustomResourceDefinition of group
    hybridsovereign.redhat whose metadata.name is <plural>.<group>,
  - contain no Helm template text ("{{").

usage:
  python3 -I scripts/gen-crds.py                 write crds.yaml
  python3 -I scripts/gen-crds.py --check         exit 1 when crds.yaml differs from the sources
  python3 -I scripts/gen-crds.py --compare FILE  compare the sources with FILE (a crds.yaml, a
                                                 multi-document CRD file or a directory of CRD
                                                 files, e.g. CRDs exported from a cluster) as data
"""
import argparse
import json
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    print("gen-crds: PyYAML is required", file=sys.stderr)
    sys.exit(2)

GROUP = "hybridsovereign.redhat"
ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "operator" / "config" / "crd" / "bases"
OUTPUT = ROOT / "operator" / "primary" / "helm" / "templates" / "crds.yaml"
HEADER = (
    "{{- /*\n"
    "Generated by scripts/gen-crds.py from operator/config/crd/bases/crd-*.yaml.\n"
    "Do not edit this file: edit the source of the kind and run `python3 -I scripts/gen-crds.py`.\n"
    "*/ -}}\n"
)
NAME_RE = re.compile(r"^crd-([a-z0-9]+)\.yaml$")
# Server-side fields that are never part of a source (stripped before a --compare).
SERVER_METADATA = ("uid", "resourceVersion", "generation", "creationTimestamp", "managedFields",
                   "selfLink", "deletionTimestamp", "finalizers", "ownerReferences")
SERVER_ANNOTATIONS = ("kubectl.kubernetes.io/last-applied-configuration",)


def fail(errors):
    for e in errors:
        print(f"gen-crds: {e}", file=sys.stderr)
    sys.exit(1)


def load_sources(src_dir=SOURCES):
    """Validate the sources; return [(path, text, crd_dict)] in file-name order."""
    errors = []
    out = []
    seen = {}
    for path in sorted(src_dir.iterdir()):
        if path.is_dir():
            errors.append(f"{path.name}: unexpected directory in {src_dir}")
            continue
        if path.name.startswith(".") or path.name == "README.md":
            continue
        m = NAME_RE.match(path.name)
        if not m:
            errors.append(f"{path.name}: not a CRD source name (expected crd-<singular>.yaml)")
            continue
        text = path.read_text()
        if "{{" in text:
            errors.append(f"{path.name}: contains template text ({{{{); sources are plain YAML")
            continue
        try:
            docs = [d for d in yaml.safe_load_all(text) if d is not None]
        except yaml.YAMLError as e:
            errors.append(f"{path.name}: YAML error: {e}")
            continue
        if len(docs) != 1:
            errors.append(f"{path.name}: {len(docs)} documents (expected exactly one CRD)")
            continue
        crd = docs[0]
        if crd.get("apiVersion") != "apiextensions.k8s.io/v1" or crd.get("kind") != "CustomResourceDefinition":
            errors.append(f"{path.name}: not an apiextensions.k8s.io/v1 CustomResourceDefinition")
            continue
        spec = crd.get("spec") or {}
        names = spec.get("names") or {}
        if spec.get("group") != GROUP:
            errors.append(f"{path.name}: spec.group is {spec.get('group')!r}, expected {GROUP}")
        if names.get("singular") != m.group(1):
            errors.append(f"{path.name}: file name does not match spec.names.singular {names.get('singular')!r}")
        want = f"{names.get('plural')}.{GROUP}"
        name = (crd.get("metadata") or {}).get("name")
        if name != want:
            errors.append(f"{path.name}: metadata.name {name!r}, expected {want}")
        for key in ("kind", "plural", "singular"):
            v = names.get(key)
            if v in seen:
                errors.append(f"{path.name}: names.{key} {v!r} also used by {seen[v]}")
            seen[v] = path.name
        out.append((path, text, crd))
    if errors:
        fail(errors)
    if not out:
        fail([f"no sources in {src_dir}"])
    return out


def render(sources):
    parts = []
    for _, text, _ in sources:
        body = text
        if body.startswith("---\n"):
            body = body[4:]
        parts.append(body.rstrip("\n") + "\n")
    return HEADER + "{{- if .Values.installCRDs }}\n" + "---\n".join(parts) + "{{- end }}\n"


def load_crd_file(path):
    """CRDs from a crds.yaml (template lines dropped), a multi-doc file, JSON or a directory."""
    path = Path(path)
    files = sorted(p for p in path.rglob("*") if p.suffix in (".yaml", ".yml", ".json")) if path.is_dir() else [path]
    crds = {}
    for f in files:
        text = f.read_text()
        if f.suffix == ".json":
            data = json.loads(text)
            docs = data.get("items", [data]) if isinstance(data, dict) else data
        else:
            text = re.sub(r"\{\{-?\s*/\*.*?\*/\s*-?\}\}", "", text, flags=re.S)  # Helm comments
            text = "\n".join(line for line in text.splitlines() if "{{" not in line)
            docs = list(yaml.safe_load_all(text))
        for d in docs:
            if isinstance(d, dict) and d.get("kind") == "CustomResourceDefinition":
                crds[d["metadata"]["name"]] = d
    return crds


def normalise(crd):
    crd = json.loads(json.dumps(crd))
    md = crd.get("metadata") or {}
    for k in SERVER_METADATA:
        md.pop(k, None)
    ann = md.get("annotations") or {}
    for k in SERVER_ANNOTATIONS:
        ann.pop(k, None)
    if not ann:
        md.pop("annotations", None)
    if not md.get("labels"):
        md.pop("labels", None)
    crd.pop("status", None)
    spec = crd.get("spec") or {}
    # API server default, never written in a source.
    if spec.get("conversion") == {"strategy": "None"}:
        spec.pop("conversion")
    return crd


def diff_paths(a, b, prefix=""):
    """Paths where a (new) and b (old) differ; "added" = only in a, "removed" = only in b."""
    if type(a) is not type(b):
        return [prefix or "/"]
    if isinstance(a, dict):
        out = []
        for k in sorted(set(a) | set(b)):
            if k not in a:
                out.append(f"{prefix}/{k} (removed)")
            elif k not in b:
                out.append(f"{prefix}/{k} (added)")
            else:
                out.extend(diff_paths(a[k], b[k], f"{prefix}/{k}"))
        return out
    if isinstance(a, list):
        if len(a) != len(b):
            return [f"{prefix} (list length {len(b)} -> {len(a)})"]
        out = []
        for i, (x, y) in enumerate(zip(a, b)):
            out.extend(diff_paths(x, y, f"{prefix}/{i}"))
        return out
    return [] if a == b else [prefix or "/"]


def compare(sources, other_path):
    """Compare sources (new) with another CRD set (old). Prints a report; returns the number of
    CRDs whose spec differs plus CRDs present on one side only."""
    new = {crd["metadata"]["name"]: normalise(crd) for _, _, crd in sources}
    old = {k: normalise(v) for k, v in load_crd_file(other_path).items()}
    bad = 0
    for name in sorted(set(new) | set(old)):
        if name not in old:
            print(f"only in sources: {name}")
            bad += 1
            continue
        if name not in new:
            print(f"only in {other_path}: {name}")
            bad += 1
            continue
        spec = diff_paths(new[name].get("spec"), old[name].get("spec"), "spec")
        meta = diff_paths(new[name].get("metadata"), old[name].get("metadata"), "metadata")
        if spec:
            bad += 1
            print(f"SPEC DIFFERS {name}: {len(spec)} path(s)")
            for p in spec[:20]:
                print(f"    {p}")
        if meta:
            print(f"metadata differs {name}: " + ", ".join(meta[:10]))
    print(f"compare: {len(new)} sources, {len(old)} in {other_path}, {bad} with a spec difference or missing")
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 when crds.yaml is not up to date")
    g.add_argument("--compare", metavar="FILE", help="compare the sources as data with FILE or a directory")
    ap.add_argument("--sources", default=str(SOURCES), help=argparse.SUPPRESS)
    ap.add_argument("--output", default=str(OUTPUT), help=argparse.SUPPRESS)
    a = ap.parse_args()
    sources = load_sources(Path(a.sources))
    if a.compare:
        return 1 if compare(sources, a.compare) else 0
    text = render(sources)
    out = Path(a.output)
    current = out.read_text() if out.exists() else ""
    if a.check:
        if current != text:
            print(f"gen-crds: {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out} is not generated from "
                  "the sources; run python3 -I scripts/gen-crds.py", file=sys.stderr)
            return 1
        print(f"gen-crds: crds.yaml up to date ({len(sources)} CRDs)")
        return 0
    if current != text:
        out.write_text(text)
        print(f"gen-crds: wrote {out} ({len(sources)} CRDs)")
    else:
        print(f"gen-crds: crds.yaml unchanged ({len(sources)} CRDs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
